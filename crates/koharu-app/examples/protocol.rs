use std::path::{Path, PathBuf};

use anyhow::{Context as _, Result, bail};
use specta_typescript::{Typescript, semantic::Configuration};

/// Generated bindings, relative to the repository root.
const PROTOCOL: &str = "packages/koharu/src/protocol.ts";

fn main() -> Result<()> {
    // The repository root is two levels above this crate; a relative `KOHARU_PROTOCOL_OUT` is
    // resolved against it, so the output never depends on the directory cargo runs from.
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let output = std::env::var_os("KOHARU_PROTOCOL_OUT")
        .map_or_else(|| root.join(PROTOCOL), |path| root.join(PathBuf::from(path)));
    koharu_app::bindings()
        .semantic_types(Configuration::empty().enable_lossless_floats())
        .export(Typescript::default().header("// generated by koharu; do not edit\n// @ts-nocheck: generated bindings are checked by their Rust source, not by strict hosts.\n"), &output)
        .with_context(|| format!("failed to generate {}", output.display()))?;
    // tauri-specta imports `invoke` and `Channel` from `@tauri-apps/api/core`; the protocol
    // takes them from `@aphrody/shenron-koharu`'s transport, which speaks Tauri IPC in the desktop app
    // and the `/api/local/koharu` bridge of shenron-server elsewhere.
    let bindings = std::fs::read_to_string(&output)
        .with_context(|| format!("failed to read {}", output.display()))?
        .replace("\"@tauri-apps/api/core\"", "\"./transport\"");
    if bindings.contains("@tauri-apps/api/") {
        bail!("the generated protocol imports another Tauri module than core");
    }
    // Callers create their channels with the transport's `Channel`.
    let bindings = format!("{bindings}\nexport {{ Channel }};\n");
    std::fs::write(&output, bindings)
        .with_context(|| format!("failed to write {}", output.display()))?;
    Ok(())
}
