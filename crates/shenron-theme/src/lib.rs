//! Semantic theme tokens and the Dragon Ball theme set of the native GPUI and NSH surfaces.
//!
//! `themes/shenron.json` is generated with the web palette from `packages/ui/src/tokens.ts`
//! (`bun packages/ui/scripts/generate-palette.ts`): the dark "Shenron Nuit" and light
//! "Shenron Jour" themes carry the measured series colours, their OKLCH tonal scales and text
//! tones chosen to reach the WCAG AA body ratio on their background.

use std::rc::Rc;
use std::time::Duration;

use gpui_kit::App;
use gpui_kit::Hsla;
use gpui_kit::base::Spring;
use gpui_kit::component::{Theme, ThemeMode, ThemeRegistry, ThemeSet};
use serde::Deserialize;

/// The generated theme set, also registered in [`ThemeRegistry`] for theme pickers.
pub const THEME_SET_JSON: &str = include_str!("../themes/shenron.json");

/// Semantic color tokens derived from the active `gpui_kit::component::Theme`.
#[derive(Clone, Copy, Debug)]
pub struct SemanticThemeTokens {
    pub background: Hsla,
    pub surface: Hsla,
    pub surface_muted: Hsla,
    pub foreground: Hsla,
    pub muted_foreground: Hsla,
    pub border: Hsla,
    pub accent: Hsla,
    pub danger: Hsla,
    pub success: Hsla,
    pub warning: Hsla,
}

impl SemanticThemeTokens {
    /// Reads semantic tokens from the active `gpui-kit` theme.
    pub fn from_theme(theme: &Theme) -> Self {
        Self {
            background: theme.background,
            surface: theme.secondary,
            surface_muted: theme.muted,
            foreground: theme.foreground,
            muted_foreground: theme.muted_foreground,
            border: theme.border,
            accent: theme.primary,
            danger: theme.danger,
            success: theme.success,
            warning: theme.warning,
        }
    }
}

/// Compose Material 3 springs, generated by `bun packages/m3-tokens/scripts/sync-compose-m3.ts`.
pub const COMPOSE_M3_SPRINGS_JSON: &str = include_str!("../themes/compose-m3-springs.json");

/// One Material 3 spring: damping ratio and stiffness (unit mass).
#[derive(Clone, Copy, Debug, Deserialize, PartialEq)]
pub struct M3Spring {
    pub damping: f32,
    pub stiffness: f32,
}

impl M3Spring {
    /// The GPUI spring with the same motion: gpui-base integrates `omega0 = TAU / response`, and a
    /// unit-mass Material spring has `omega0 = sqrt(stiffness)`.
    pub fn to_gpui(self) -> Spring {
        Spring::new(Duration::from_secs_f32(std::f32::consts::TAU / self.stiffness.sqrt())).with_damping(self.damping)
    }
}

/// The Expressive scheme of Compose Material 3, the one the Shenron surfaces animate with.
#[derive(Clone, Copy, Debug, Deserialize)]
pub struct M3ExpressiveSprings {
    #[serde(rename = "fast-spatial")]
    pub fast_spatial: M3Spring,
    #[serde(rename = "default-spatial")]
    pub default_spatial: M3Spring,
    #[serde(rename = "default-effects")]
    pub default_effects: M3Spring,
}

#[derive(Deserialize)]
struct SpringSnapshot {
    expressive: M3ExpressiveSprings,
}

/// Parses [`COMPOSE_M3_SPRINGS_JSON`].
pub fn expressive_springs() -> M3ExpressiveSprings {
    serde_json::from_str::<SpringSnapshot>(COMPOSE_M3_SPRINGS_JSON)
        .expect("themes/compose-m3-springs.json is generated valid")
        .expressive
}

/// Parses [`THEME_SET_JSON`].
pub fn theme_set() -> ThemeSet {
    serde_json::from_str(THEME_SET_JSON).expect("themes/shenron.json is generated valid")
}

/// Installs the Shenron light and dark themes and switches to `mode`.
pub fn init(cx: &mut App, mode: ThemeMode) {
    if let Err(error) = ThemeRegistry::global_mut(cx).load_themes_from_str(THEME_SET_JSON) {
        panic!("themes/shenron.json does not load: {error}");
    }
    let set = theme_set();
    Theme::update(cx, |theme| {
        for config in set.themes {
            let config = Rc::new(config);
            if config.mode.is_dark() {
                theme.dark_theme = config;
            } else {
                theme.light_theme = config;
            }
        }
    });
    Theme::change(mode, None, cx);
    let springs = expressive_springs();
    Theme::update(cx, |theme| {
        // Controls (switch thumbs, toggles) move with the fast spatial spring, layout moves with the
        // default one; the pixel tolerance of the stock move spring is kept.
        theme.motion.spring_control = springs.fast_spatial.to_gpui();
        theme.motion.spring_move = springs.default_spatial.to_gpui().with_epsilon(theme.motion.spring_move.epsilon());
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    use gpui_kit::component::try_parse_color;
    use gpui_kit::px;

    fn color(hex: &str) -> Hsla {
        try_parse_color(hex).expect("valid hex")
    }

    #[gpui_kit::test]
    fn dark_mode_applies_shenron_nuit(cx: &mut gpui_kit::TestAppContext) {
        cx.update(|cx| {
            gpui_kit::init(cx);
            init(cx, ThemeMode::Dark);
            let theme = Theme::global(cx);
            let tokens = SemanticThemeTokens::from_theme(theme);
            assert_eq!(theme.theme_name().as_ref(), "Shenron Nuit");
            assert_eq!(theme.font_size, px(14.0));
            assert_eq!(tokens.background, color("#0a0a0a"));
            assert_eq!(tokens.accent, color("#e78220"));
            assert_eq!(theme.primary_foreground, color("#0a0a0a"));
        });
    }

    #[gpui_kit::test]
    fn light_mode_applies_shenron_jour(cx: &mut gpui_kit::TestAppContext) {
        cx.update(|cx| {
            gpui_kit::init(cx);
            init(cx, ThemeMode::Light);
            let theme = Theme::global(cx);
            assert_eq!(theme.theme_name().as_ref(), "Shenron Jour");
            assert_eq!(theme.background, color("#efe9d8"));
            assert_eq!(theme.foreground, color("#131b08"));
        });
    }

    #[test]
    fn material_springs_convert_to_the_same_natural_frequency() {
        let spring = expressive_springs().default_spatial;
        assert_eq!((spring.damping, spring.stiffness), (0.8, 380.0));
        let response = std::f32::consts::TAU / spring.stiffness.sqrt();
        assert!((response - 0.3223).abs() < 1e-3, "response {response}");
    }

    #[test]
    fn theme_set_has_one_theme_per_mode() {
        let set = theme_set();
        let dark = set.themes.iter().filter(|config| config.mode.is_dark()).count();
        assert_eq!((set.themes.len(), dark), (2, 1));
    }
}
