use crate::types::{AuraType, FighterId, FighterStyle};
use serde::{Deserialize, Serialize};

/// Spécification d'une transformation avec multiplicateur de puissance et type d'aura.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct FormDefinition {
    pub level: u32,
    pub name: String,
    pub name_ja: String,
    pub power_multiplier: f32,
    pub power_level: u64,
    pub aura: AuraType,
    pub aura_color: [f32; 4],
}

/// Spécification d'une attaque spéciale ou rayon Kikōha.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SpecialMoveDefinition {
    pub id: String,
    pub name: String,
    pub name_ja: String,
    pub ki_cost: f32,
    pub damage: f32,
    pub is_beam: bool,
    pub is_ultimate: bool,
    pub color: [f32; 4],
    pub sfx: String,
}

/// Définition canonique d'un guerrier légendaire.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct FighterDefinition {
    pub id: FighterId,
    pub name: String,
    pub name_ja: String,
    pub style: FighterStyle,
    pub base_hp: f32,
    pub base_ki: f32,
    pub base_power_level: u64,
    pub emblem: String,
    pub forms: Vec<FormDefinition>,
    pub specials: Vec<SpecialMoveDefinition>,
}

/// Dialogue de scénario pour le mode histoire.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DialogueLine {
    pub speaker: String,
    pub text: String,
}

/// Chapitre du Mode Histoire (15 chapitres couvrant les 42 tomes de Toriyama).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct StoryChapter {
    pub id: u32,
    pub tome: u32,
    pub saga: String,
    pub title: String,
    pub title_ja: String,
    pub arena_id: String,
    pub player_fighter: FighterId,
    pub enemy_fighter: FighterId,
    pub enemy_name: String,
    pub intro_dialogue: Vec<DialogueLine>,
    pub victory_dialogue: Vec<DialogueLine>,
    pub objective: String,
    pub boss_hp: f32,
    pub target_transformation: Option<u32>,
}

