/**
 * Builds the single-file Activity server: the client bundle and the server in one executable.
 *
 *   bun scripts/compile.ts                      host platform  -> dist/bin/shenron-activity[.exe]
 *   bun scripts/compile.ts --target linux-x64   cross-compile (linux-x64 | windows-x64 | darwin-arm64)
 *   bun scripts/compile.ts --outfile <path>
 *
 * How: the production client is built (`scripts/build.ts`), then a generated entry imports every
 * file of the bundle with `with { type: "file" }`, which makes `bun build --compile` embed them, and
 * starts the server on an `embeddedAssets` store instead of reading `dist/client` from the disk.
 * The result needs nothing next to it: `SHENRON_ACTIVITY_*`, `DISCORD_CLIENT_*` and the secrets come
 * from the environment as for `bun src/main.ts`.
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { APP_ROOT, buildClient } from "./build";

const TARGETS = new Set(["linux-x64", "linux-arm64", "windows-x64", "darwin-x64", "darwin-arm64"]);

function walk(dir: string, base = dir): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? walk(join(dir, entry.name), base)
      : [relative(base, join(dir, entry.name)).split("\\").join("/")],
  );
}

export async function compileServer(options: { target?: string; outfile?: string } = {}) {
  const target = options.target;
  if (target && !TARGETS.has(target)) throw new Error(`unknown target ${target}`);
  const windows =
    (target ?? process.platform) === "windows-x64" || (!target && process.platform === "win32");
  const outfile = resolve(
    options.outfile ?? join(APP_ROOT, "dist", "bin", `shenron-activity${windows ? ".exe" : ""}`),
  );

  const client = await buildClient({ mock: false });
  const work = join(APP_ROOT, "dist", "compile");
  rmSync(work, { recursive: true, force: true });
  mkdirSync(work, { recursive: true });

  const files = walk(client.outdir);
  const imports = files.map(
    (file, index) =>
      `import f${index} from ${JSON.stringify(relative(work, join(client.outdir, file)).split("\\").join("/"))} with { type: "file" };`,
  );
  const entries = files.map((file, index) => `  ${JSON.stringify(file)}: f${index},`);
  const entry = join(work, "entry.ts");
  writeFileSync(
    entry,
    `// Generated by scripts/compile.ts: do not edit.
import { embeddedAssets } from "../../src/http/assets";
import { run } from "../../src/run";
${imports.join("\n")}

run(embeddedAssets({
${entries.join("\n")}
}));
`,
  );

  mkdirSync(join(outfile, ".."), { recursive: true });
  const result = await Bun.build({
    entrypoints: [entry],
    target: "bun",
    minify: true,
    compile: target ? { target: `bun-${target}` as never, outfile } : { outfile },
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
  });
  if (!result.success) {
    for (const log of result.logs) console.error(String(log));
    throw new Error("compile failed");
  }
  return { outfile, embedded: files.length, bytes: Bun.file(outfile).size };
}

if (import.meta.main) {
  const args = Bun.argv.slice(2);
  const option = (name: string) => {
    const index = args.indexOf(name);
    return index >= 0 ? args[index + 1] : undefined;
  };
  const result = await compileServer({ target: option("--target"), outfile: option("--outfile") });
  console.log(`${result.outfile} (${result.bytes} bytes, ${result.embedded} embedded files)`);
}
