/**
 * The design tokens of the Activity: `@aphrody/shenron-ui` owns the palette (`tokens.ts`, generated
 * from `styles.css`), the Activity writes it as CSS custom properties into its bundle. Nothing is
 * copied by hand, so a change of palette reaches the Activity at its next build.
 */
import { colorVars, tokens } from "@aphrody/shenron-ui/tokens";

const HEX = /^#[0-9a-f]{3,8}$/i;

/** `:root { --dbz-bg: #0a0a0a; ... }` for every token that is a plain colour. */
export function tokensCss(): string {
  const lines: string[] = [];
  for (const [name, variable] of Object.entries(colorVars)) {
    const value = tokens.color[name as keyof typeof tokens.color];
    if (HEX.test(value)) lines.push(`  ${variable}: ${value};`);
  }
  return `/* Generated by scripts/tokens.ts from @aphrody/shenron-ui/tokens. */\n:root {\n${lines.join("\n")}\n}\n`;
}
