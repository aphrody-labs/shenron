#!/usr/bin/env bun
// SPDX-License-Identifier: Apache-2.0
/**
 * Stages the reverse-engineering WebAssembly module (`shenron-re`, built in aphrody-labs/wiki)
 * into `src/wasm/` (tracked by Git) and the content-hashed copy under `apps/site/public/wasm/`,
 * then rewrites `src/wasm/re-wasm-asset.ts`.
 *
 *   bun packages/pipeline/scripts/sync-re-wasm.ts [<wasm-bindgen output dir>]
 *
 * The source is the argument, else `SHENRON_RE_WASM_DIR`, else `<wiki>/crates/shenron-re/pkg`
 * (`SHENRON_WIKI_DIR`, default `../wiki`); it holds the `wasm-bindgen --target web` output.
 * Nothing is compiled here.
 */
import { createHash } from "node:crypto";
import { copyFile, mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { wikiDir } from "@aphrody/shenron-config/wiki-artifacts";

const ROOT = join(import.meta.dir, "..", "..", "..");
const OUT_DIR = join(ROOT, "packages", "pipeline", "src", "wasm");
const SITE_WASM_DIR = join(ROOT, "apps", "site", "public", "wasm");
const FILES = [
  "shenron_re.d.ts",
  "shenron_re.js",
  "shenron_re_bg.wasm",
  "shenron_re_bg.wasm.d.ts",
] as const;

try {
  const source = Bun.argv[2] ?? wikiDir("SHENRON_RE_WASM_DIR", "crates/shenron-re/pkg");
  const missing = FILES.filter((file) => !Bun.file(join(source, file)).size);
  if (missing.length) throw new Error(`${source} lacks ${missing.join(", ")}`);

  await mkdir(OUT_DIR, { recursive: true });
  for (const file of FILES) await copyFile(join(source, file), join(OUT_DIR, file));
  // `wasm-bindgen --target web` emits a self-contained glue file: no separate `_bg.js` shim.
  await rm(join(OUT_DIR, "shenron_re_bg.js"), { force: true });

  const wasmBytes = await Bun.file(join(source, "shenron_re_bg.wasm")).bytes();
  const sha256 = createHash("sha256").update(wasmBytes).digest("hex");
  const filename = `shenron_re_bg.${sha256.slice(0, 16)}.wasm`;
  await mkdir(SITE_WASM_DIR, { recursive: true });
  await copyFile(join(source, "shenron_re_bg.wasm"), join(SITE_WASM_DIR, filename));
  await writeFile(
    join(OUT_DIR, "re-wasm-asset.ts"),
    `// SPDX-License-Identifier: Apache-2.0\n// Generated by packages/pipeline/scripts/sync-re-wasm.ts.\n` +
      `export const SHENRON_RE_WASM_FILENAME = ${JSON.stringify(filename)};\n` +
      `export const SHENRON_RE_WASM_SHA256 = ${JSON.stringify(sha256)};\n`,
  );
  console.log(
    `shenron-re wasm synced from ${source} to ${OUT_DIR} and ${SITE_WASM_DIR}/${filename}`,
  );
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
