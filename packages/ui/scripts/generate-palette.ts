/**
 * Generates the OKLCH palette layer and its contrast report from the measured `--dbz-*` tokens.
 *
 *   bun packages/ui/scripts/generate-palette.ts          write both files
 *   bun packages/ui/scripts/generate-palette.ts --check  exit 1 when a file is stale
 *
 * Input: `tokens.color` (the stylesheet defaults, themselves measured on manga, colour editions and
 * anime frames: see plugin/skills/toriyama-svg/references/mesures). Output: `palette.generated.css`
 * (tonal scales as hex custom properties plus their OKLCH twins) and `docs/design/contrast-report.md`
 * (WCAG 2.x ratio and APCA Lc of every token as text on the page and card backgrounds).
 */
import { join } from "node:path";
import { tokens } from "../src/tokens";
import { SCALE_STEPS, apcaLc, contrastRatio, hexToOklch, tonalScale } from "../src/design-system/colorimetry";

const PACKAGE = join(import.meta.dir, "..");
export const PALETTE_PATH = join(PACKAGE, "src", "design-system", "palette.generated.css");
export const REPORT_PATH = join(PACKAGE, "..", "..", "docs", "design", "contrast-report.md");

/** Measured hues that get a full tonal scale: the identity colours of the series. */
const SCALED = ["orange", "blue", "gold", "green", "red", "cyan", "purple"] as const;
const BACKGROUNDS = ["bg", "card"] as const;
const AA_RATIO = 4.5;
const APCA_BODY = 60;

const colors = tokens.color as Record<string, string>;
const kebab = (name: string) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

function paletteCss(): string {
  const lines = [
    "/* Generated by packages/ui/scripts/generate-palette.ts from tokens.ts; do not edit. */",
    ":root {",
  ];
  for (const name of SCALED) {
    const base = colors[name];
    if (!base) throw new Error(`token ${name} missing`);
    const scale = tonalScale(base);
    for (const step of SCALE_STEPS) {
      const hex = scale[step];
      const { l, c, h } = hexToOklch(hex);
      lines.push(`  --dbz-${name}-${step}: ${hex.toLowerCase()};`);
      lines.push(`  --dbz-${name}-${step}-oklch: oklch(${l.toFixed(3)} ${c.toFixed(3)} ${h.toFixed(1)});`);
    }
  }
  lines.push("}", "");
  return lines.join("\n");
}

function reportMarkdown(): string {
  const rows: string[] = [];
  let failing = 0;
  for (const [name, hex] of Object.entries(colors).sort(([a], [b]) => a.localeCompare(b))) {
    if (!/^#[0-9a-f]{6}$/i.test(hex) || BACKGROUNDS.includes(name as (typeof BACKGROUNDS)[number])) continue;
    const cells = BACKGROUNDS.map((background) => {
      const ratio = contrastRatio(hex, colors[background]!);
      const lc = Math.abs(apcaLc(hex, colors[background]!));
      return { ratio, lc };
    });
    const pass = cells.every((cell) => cell.ratio >= AA_RATIO);
    if (!pass) failing++;
    const oklch = hexToOklch(hex);
    rows.push(
      `| \`--dbz-${kebab(name)}\` | ${hex.toUpperCase()} | ${oklch.l.toFixed(3)} / ${oklch.c.toFixed(3)} / ${oklch.h.toFixed(0)} | ${cells
        .map((cell) => `${cell.ratio.toFixed(2)} (Lc ${cell.lc.toFixed(0)})`)
        .join(" | ")} | ${pass ? "yes" : "no"} |`,
    );
  }
  return [
    "# Contrast of the design tokens",
    "",
    "Generated by `bun packages/ui/scripts/generate-palette.ts` from `packages/ui/src/tokens.ts`; do not edit.",
    "",
    `Each token is measured as text on the page background (\`bg\` ${colors.bg}) and on the card background (\`card\` ${colors.card}). Ratio: WCAG 2.x; Lc: APCA (0.0.98G-4g), absolute value. Threshold for body text: ratio ${AA_RATIO}, Lc ${APCA_BODY}. A token below the threshold stays valid for borders, large display text and fills.`,
    "",
    `${failing} of ${rows.length} tokens are below the body-text ratio on at least one background.`,
    "",
    "| Token | Hex | OKLCH (L / C / h) | on bg | on card | Body text |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const outputs: [string, string][] = [
    [PALETTE_PATH, paletteCss()],
    [REPORT_PATH, reportMarkdown()],
  ];
  if (process.argv.includes("--check")) {
    let stale = false;
    for (const [path, content] of outputs) {
      const current = await Bun.file(path).text().catch(() => "");
      if (current !== content) {
        console.error(`${path} is stale: run bun packages/ui/scripts/generate-palette.ts`);
        stale = true;
      }
    }
    process.exit(stale ? 1 : 0);
  }
  for (const [path, content] of outputs) await Bun.write(path, content);
  console.log(`palette: ${SCALED.length} scales; report: ${REPORT_PATH}`);
}
