/**
 * Embed the public agent home template (`templates/agent-home`, the seven native documents of
 * aphrody-agent-home) into `src/agent-homes/template.generated.ts`, so that the package and the
 * compiled binaries (bot, shenron-server) carry it without reading the repository.
 *
 *   bun packages/db/scripts/agent-home-template.ts           # regenerate
 *   bun packages/db/scripts/agent-home-template.ts --check   # exit 1 on drift (CI)
 */
import { mkdtempSync, rmSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { AGENT_HOME_DOCUMENTS } from "../src/agent-homes/types";

const ROOT = resolve(import.meta.dir, "../../..");
const OUT = join(import.meta.dir, "../src/agent-homes/template.generated.ts");

export async function renderTemplateModule(root = ROOT): Promise<string> {
  const lines = [
    "// SPDX-License-Identifier: Apache-2.0",
    "// Generated by packages/db/scripts/agent-home-template.ts from templates/agent-home: do not edit.",
    'import type { AgentHomeDocument } from "./types";',
    "",
    "export const TEMPLATE_DOCUMENTS: Record<AgentHomeDocument, string> = {",
  ];
  for (const name of AGENT_HOME_DOCUMENTS) {
    const text = await Bun.file(join(root, "templates/agent-home", name)).text();
    lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(text)},`);
  }
  lines.push("};", "");
  return lines.join("\n");
}

/** The module as the repository formatter writes it (oxfmt, Rust, on PATH like `format:check`). */
async function formatted(source: string): Promise<string> {
  const oxfmt = Bun.which("oxfmt");
  if (!oxfmt) throw new Error("oxfmt not found on PATH");
  // Keep the candidate beside the output so oxfmt resolves the same repository config.
  // oxfmt 0.72 supports file formatting but has no --stdin-filepath option.
  const dir = mkdtempSync(join(dirname(OUT), ".agent-home-template-"));
  const candidate = join(dir, basename(OUT));
  try {
    await Bun.write(candidate, source);
    const child = Bun.spawnSync([oxfmt, "--write", candidate], {
      stdout: "ignore",
      stderr: "inherit",
    });
    if (child.exitCode !== 0) throw new Error("oxfmt failed");
    return await Bun.file(candidate).text();
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  const next = await formatted(await renderTemplateModule());
  const current = await Bun.file(OUT)
    .text()
    .catch(() => "");
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error(`${OUT} is stale: bun packages/db/scripts/agent-home-template.ts`);
      process.exit(1);
    }
    console.log("✓ agent home template embedded");
  } else {
    await Bun.write(OUT, next);
    console.log(`written ${OUT}`);
  }
}
