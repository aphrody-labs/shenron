#!/usr/bin/env bun
// SPDX-License-Identifier: Apache-2.0
/**
 * Regenerates `[workspace.dependencies]` of the root Cargo.toml from the
 * manifests of `crates/*` and the pinned Aphrody revision.
 *
 * - Shenron crates (`crates/<name>`) become `path` dependencies.
 * - Aphrody crates (path dependencies in Aphrody's workspace at `APHRODY_REV`)
 *   become `git` dependencies on aphrody-labs/aphrody pinned by `rev`.
 * - Everything else (crates.io, other git sources) is copied verbatim from
 *   Aphrody's workspace so versions and features stay in step.
 * - Dependencies only Shenron uses are declared by hand above the generated
 *   block (Shenron-owned section) and are left untouched.
 *
 * Usage: bun scripts/build/rust/workspace-deps.ts [--aphrody <checkout>] [--rev <sha>] [--check]
 * The Aphrody repository is only read through `git show <rev>:Cargo.toml`: `--aphrody`, else
 * ~/aphrody, else the git database Cargo keeps after fetching the pinned revision
 * ($CARGO_HOME/git/db/aphrody-*; enough in CI, where no checkout exists).
 */
import { $ } from "bun";
import { existsSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const ROOT = `${join(import.meta.dir, "../../..")}/`;
const args = process.argv.slice(2);
const flag = (name: string) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const manifestPath = `${ROOT}Cargo.toml`;
const manifest = await Bun.file(manifestPath).text();
const currentRev = manifest.match(/^# aphrody-rev: ([0-9a-f]{40})$/m)?.[1];
const REV = flag("--rev") ?? currentRev;
if (!REV || !/^[0-9a-f]{40}$/.test(REV)) throw new Error("--rev <40-hex sha> is required");
const GIT = "https://github.com/aphrody-labs/aphrody";

/** Repositories that may hold `REV`, in order of preference. */
function aphrodyRepositories(): string[] {
  const explicit = flag("--aphrody");
  if (explicit) return [explicit];
  const db = join(process.env.CARGO_HOME ?? join(homedir(), ".cargo"), "git/db");
  const fetched = existsSync(db)
    ? [...new Bun.Glob("aphrody-*").scanSync({ cwd: db, onlyFiles: false })].sort()
    : [];
  return [join(homedir(), "aphrody"), ...fetched.map((name) => join(db, name))];
}

async function upstreamManifest(): Promise<string> {
  const tried: string[] = [];
  for (const repo of aphrodyRepositories()) {
    const show = await $`git -C ${repo} show ${REV}:Cargo.toml`.quiet().nothrow();
    if (show.exitCode === 0) return show.text();
    tried.push(repo);
  }
  throw new Error(
    `Aphrody ${REV} not found in ${tried.join(", ") || "any repository"}: pass --aphrody <checkout> or run \`cargo fetch\``,
  );
}

type Spec = string | Record<string, unknown>;
const upstream = Bun.TOML.parse(await upstreamManifest()) as {
  workspace: { dependencies: Record<string, Spec> };
};
const deps = upstream.workspace.dependencies;

const begin = "# BEGIN generated by scripts/build/rust/workspace-deps.ts";
const end = "# END generated";
const handWritten = Bun.TOML.parse(
  manifest.replace(new RegExp(`${begin}[\\s\\S]*?${end}`), ""),
) as {
  workspace: { dependencies?: Record<string, Spec> };
};
const owned = new Set(Object.keys(handWritten.workspace.dependencies ?? {}));
const local = new Map<string, { path: string; version: string }>();
const wanted = new Set<string>();
const ws = handWritten as unknown as { workspace: { package: { version: string } } };
for await (const file of new Bun.Glob("crates/*/Cargo.toml").scan(ROOT)) {
  const crate = Bun.TOML.parse(await Bun.file(ROOT + file).text()) as Record<string, any>;
  const pkg = crate.package as { name: string; version: string | { workspace: true } };
  const version = typeof pkg.version === "string" ? pkg.version : ws.workspace.package.version;
  local.set(pkg.name, { path: file.replace(/\/Cargo\.toml$/, ""), version });
  const tables: Record<string, Spec>[] = [];
  for (const key of ["dependencies", "dev-dependencies", "build-dependencies"]) {
    if (crate[key]) tables.push(crate[key]);
  }
  for (const target of Object.values((crate.target ?? {}) as Record<string, any>)) {
    for (const key of ["dependencies", "dev-dependencies", "build-dependencies"]) {
      if (target[key]) tables.push(target[key]);
    }
  }
  for (const table of tables) {
    for (const [name, spec] of Object.entries(table)) {
      if (typeof spec === "object" && spec.workspace === true) wanted.add(name);
    }
  }
}

const quote = (value: unknown): string => {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "boolean" || typeof value === "number") return String(value);
  if (Array.isArray(value)) return `[${value.map(quote).join(", ")}]`;
  throw new Error(`unsupported TOML value ${JSON.stringify(value)}`);
};
const inline = (spec: Record<string, unknown>) =>
  `{ ${Object.entries(spec)
    .map(([k, v]) => `${k} = ${quote(v)}`)
    .join(", ")} }`;

const lines: string[] = [];
const missing: string[] = [];
for (const name of [...wanted].sort()) {
  if (owned.has(name)) continue;
  const own = local.get(name);
  if (own) {
    lines.push(`${name} = ${inline({ path: own.path, version: own.version })}`);
    continue;
  }
  const spec = deps[name];
  if (spec === undefined) {
    missing.push(name);
    continue;
  }
  if (typeof spec === "string") {
    lines.push(`${name} = ${quote(spec)}`);
    continue;
  }
  const { path, ...rest } = spec as Record<string, unknown>;
  if (typeof path === "string") {
    const { features, ...other } = rest;
    const out: Record<string, unknown> = { git: GIT, rev: REV, ...other };
    if (Array.isArray(features) && features.length) out.features = features;
    lines.push(`${name} = ${inline(out)}`);
  } else {
    lines.push(`${name} = ${inline(rest)}`);
  }
}
if (missing.length)
  throw new Error(
    `declare in the Shenron-owned section (not in Aphrody's workspace): ${missing.join(", ")}`,
  );

const block = `${begin}\n# aphrody-rev: ${REV}\n${lines.join("\n")}\n${end}`;
const next = manifest.replace(new RegExp(`${begin}[\\s\\S]*?${end}`), block);
if (args.includes("--check")) {
  if (next !== manifest) {
    console.error(
      "Cargo.toml [workspace.dependencies] is stale; run scripts/build/rust/workspace-deps.ts",
    );
    process.exit(1);
  }
} else {
  await Bun.write(manifestPath, next);
  console.log(`${lines.length} workspace dependencies (Aphrody ${REV.slice(0, 12)})`);
}
