#!/usr/bin/env bun
// SPDX-License-Identifier: Apache-2.0
/**
 * Writes the untracked `.cargo/config.toml` that patches every Aphrody git
 * dependency of the workspace to a local Aphrody checkout, so the workspace
 * builds against the checkout (and its uncommitted work) without fetching
 * aphrody-labs/aphrody. `.cargo/config.toml` is ignored by git.
 *
 * Cargo still loads the pinned git source once to lock a patched dependency;
 * `--fetch` performs that resolution from the local checkout's object store
 * (git `insteadOf`, no network), after which the lockfile keeps it offline.
 *
 * Usage: bun scripts/build/rust/local-aphrody-patch.ts [<aphrody checkout>]   (default ~/aphrody)
 *        bun scripts/build/rust/local-aphrody-patch.ts [<checkout>] --fetch
 *        bun scripts/build/rust/local-aphrody-patch.ts --remove
 */
import { mkdirSync, rmSync } from "node:fs";

const ROOT = new URL("../../../", import.meta.url).pathname;
const target = `${ROOT}.cargo/config.toml`;
if (process.argv.includes("--remove")) {
  rmSync(target, { force: true });
  console.log(`removed ${target}`);
  process.exit(0);
}
const positional = process.argv.slice(2).filter((arg) => !arg.startsWith("--"));
const checkout = (positional[0] ?? `${process.env.HOME}/aphrody`).replace(/\/+$/, "");
const GIT = "https://github.com/aphrody-labs/aphrody";

const manifest = Bun.TOML.parse(await Bun.file(`${ROOT}Cargo.toml`).text()) as {
  workspace: { dependencies: Record<string, string | Record<string, unknown>> };
};
// Package name -> directory, from the package manifests of the checkout.
const dirs = new Map<string, string>();
for await (const file of new Bun.Glob("crates/*/*/Cargo.toml").scan(checkout)) {
  const text = await Bun.file(`${checkout}/${file}`).text();
  const name = text.match(/^\[package\][\s\S]*?^name\s*=\s*"([^"]+)"/m)?.[1];
  if (name) dirs.set(name, `${checkout}/${file.replace(/\/Cargo\.toml$/, "")}`);
}
const lines: string[] = [];
for (const [name, spec] of Object.entries(manifest.workspace.dependencies)) {
  if (typeof spec !== "object" || spec.git !== GIT) continue;
  const pkg = typeof spec.package === "string" ? spec.package : name;
  const path = dirs.get(pkg);
  if (!path) throw new Error(`${pkg}: no package directory in ${checkout}/crates`);
  lines.push(`${pkg} = { path = ${JSON.stringify(path)} }`);
}
mkdirSync(`${ROOT}.cargo`, { recursive: true });
await Bun.write(
  target,
  `# Generated by scripts/build/rust/local-aphrody-patch.ts; untracked (local builds only).\n` +
    `[patch.${JSON.stringify(GIT)}]\n${lines.sort().join("\n")}\n`,
);
console.log(`${lines.length} Aphrody crates patched to ${checkout}`);

if (process.argv.includes("--fetch")) {
  // The longest matching insteadOf wins over the user's ssh rewrite of aphrody-labs/.
  const env = {
    ...process.env,
    GIT_CONFIG_COUNT: "1",
    GIT_CONFIG_KEY_0: `url.file://${checkout}/.git.insteadOf`,
    GIT_CONFIG_VALUE_0: GIT,
  };
  const fetch = Bun.spawnSync(["cargo", "metadata", "--format-version", "1"], {
    cwd: ROOT,
    env,
    stdout: "ignore",
    stderr: "inherit",
  });
  if (fetch.exitCode !== 0) process.exit(fetch.exitCode ?? 1);
  console.log("pinned Aphrody revision resolved from the local object store");
}
