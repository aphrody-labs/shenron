const LIGATURES: Readonly<Record<string, string>> = { œ: "oe", æ: "ae", ß: "ss", ø: "o", ł: "l" };

export function slugOf(text: string): string {
  const slug = text
    .normalize("NFKD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[œæßøł]/g, (c) => LIGATURES[c]!)
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug || "term";
}

/** Add `values` to `list` unless one folds like a form the term already has. */
function addAliases(list: string[], values: readonly string[], taken: Set<string>): void {
  for (const value of values) {
    const key = fold(value);
    if (!key || taken.has(key)) continue;
    taken.add(key);
    list.push(value);
  }
}

export function importLegacy(rows: { ja: string; fr: string; kind: LegacyKind }[]): LexiconData {
  // Rows sharing a French form and a kind are one term; the longest spelling leads.
  const groups = new Map<string, { ja: string[]; fr: string; kind: LegacyKind }>();
  const ordered = rows.toSorted((a, b) => codePoints(b.ja) - codePoints(a.ja));
  for (const row of ordered) {
    const key = `${row.kind}\u0000${row.fr}`;
    const group = groups.get(key) ?? { ja: [], fr: row.fr, kind: row.kind };
    if (!group.ja.includes(row.ja)) group.ja.push(row.ja);
    groups.set(key, group);
  }
  const drafts: Omit<Term, "id">[] = [];
  for (const group of groups.values()) {
    const [ja, ...otherJa] = group.ja as [string, ...string[]];
    const seed = [ja, ...otherJa].map((spelling) => ENGLISH[spelling]).find(Boolean);
    const kind =
      KIND_BY_JA[ja] ??
      (group.kind === "autre"
        ? "other"
        : KIND_OF_LEGACY[group.kind as Exclude<LegacyKind, "autre">]);
    const term: Omit<Term, "id"> = { kind, ja, fr: group.fr, en: seed?.en ?? "" };
    if (seed?.romaji) term.romaji = seed.romaji;
    const aliases: Aliases = {};
    if (otherJa.length) aliases.ja = otherJa;
    for (const lang of ["fr", "en"] as const) {
      const taken = new Set([fold(term.fr), fold(term.en)].filter(Boolean));
      for (const other of LANGS) for (const v of aliases[other] ?? []) taken.add(fold(v));
      const list: string[] = [];
      addAliases(list, seed?.aliases?.[lang] ?? [], taken);
      if (list.length) aliases[lang] = list;
    }
    if (Object.keys(aliases).length) term.aliases = aliases;
    if (seed) {
      const sources: Source[] = [];
      if (seed.en) sources.push({ lang: "en", ref: seed.ref });
      if (seed.romaji) sources.push({ lang: "romaji", ref: seed.ref });
      if (sources.length) term.sources = sources;
    }
    drafts.push(term);
  }
  // English slug of the English form, else of the French one; a shared slug takes the kind,
  // then a counter in Japanese order.
  const base = drafts.map((term) => slugOf(term.en || term.fr));
  const count = new Map<string, number>();
  for (const slug of base) count.set(slug, (count.get(slug) ?? 0) + 1);
  const ids = base.map((slug, index) =>
    (count.get(slug) ?? 0) > 1 ? `${slug}-${drafts[index]!.kind}` : slug,
  );
  const seen = new Map<string, number>();
  const order = drafts
    .map((_, index) => index)
    .toSorted((a, b) => (drafts[a]!.ja < drafts[b]!.ja ? -1 : 1));
  const finalIds: string[] = [];
  for (const index of order) {
    const id = ids[index]!;
    const n = (seen.get(id) ?? 0) + 1;
    seen.set(id, n);
    finalIds[index] = n === 1 ? id : `${id}-${n}`;
  }
  const terms: Term[] = [];
  drafts.forEach((term, index) => terms.push(Object.assign({ id: finalIds[index]! }, term)));
  return { version: 1, terms };
}

// ── CLI ─────────────────────────────────────────────────────────────────────

async function main(args: string[]): Promise<number> {
  const command = args.includes("--check") ? "check" : (args[0] ?? "build");
  if (command === "import") {
    if (existsSync(join(ROOT, TERMS)) && !args.includes("--force")) {
      console.error(`${TERMS} exists: it is the source now (import --force rebuilds it).`);
      return 1;
    }
    const rows = JSON.parse(readFileSync(join(ROOT, LEGACY), "utf8")) as {
      ja: string;
      fr: string;
      kind: LegacyKind;
    }[];
    const data = importLegacy(rows);
    const issues = validateLexicon(data);
    if (issues.length) {
      console.error(issues.join("\n"));
      return 1;
    }
    await Bun.write(join(ROOT, TERMS), renderTerms(data));
    console.log(`${TERMS}: ${data.terms.length} terms from ${rows.length} legacy rows`);
    return main(["build"]);
  }
  if (command === "build" || command === "check") {
    const { issues, outputs, lexicon } = check();
    if (issues.length) {
      console.error(issues.join("\n"));
      return 1;
    }
    const drift: string[] = [];
    for (const output of outputs) {
      const file = join(ROOT, output.path);
      const current = existsSync(file) ? readFileSync(file, "utf8") : null;
      if (current === output.content) continue;
      if (command === "check") drift.push(output.path);
      else writeFileSync(file, output.content);
    }
    if (drift.length) {
      console.error(
        `out of date: ${drift.join(", ")} — run \`bun ${SELF} build\` and commit the result.`,
      );
      return 1;
    }
    console.log(
      `${TERMS}: ${lexicon!.size} terms, ${command === "check" ? "derived outputs up to date" : "derived outputs written"}`,
    );
    return 0;
  }
  if (command === "coverage") {
    const { issues, lexicon } = check();
    if (issues.length || !lexicon) {
      console.error(issues.join("\n"));
      return 1;
    }
    if (args.includes("--json")) console.log(JSON.stringify(lexicon.coverage(), null, 2));
    else console.log(coverageReport(lexicon));
    return 0;
  }
  console.error(`usage: bun ${SELF} build | --check | coverage [--json] | import --force`);
  return 1;
}

if (import.meta.main) process.exit(await main(process.argv.slice(2)));
