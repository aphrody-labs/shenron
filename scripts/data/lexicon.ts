/**
 * lexicon.ts — the canonical Dragon Ball lexicon (`data/lexicon/terms.json`) and its derived
 * outputs.
 *
 *   bun scripts/data/lexicon.ts build            # validate, then write the derived outputs
 *   bun scripts/data/lexicon.ts --check          # validate and fail on any drifted output (CI)
 *   bun scripts/data/lexicon.ts coverage [--json] # coverage per language and per kind
 *   bun scripts/data/lexicon.ts import --force   # one-off migration from the legacy file
 *
 * Source: `data/lexicon/terms.json` (schema `data/lexicon/terms.schema.json`), edited by hand.
 * Derived outputs, never edited:
 *   - `packages/lexicon/src/terms.generated.ts`: the data embedded by `@shenron/lexicon/data`;
 *   - `data/lexique-db-canonique.json`: the legacy `{ ja, fr, kind, length }[]` read by the
 *     consumers not yet on `@shenron/lexicon` or `shenron-lexicon` (end of life:
 *     docs/architecture/lexicon.md).
 * The Rust crate `shenron-lexicon` embeds `terms.json` itself (`include_str!`).
 *
 * `import` rebuilt `terms.json` from the legacy file once (2026-10-05): rows grouped by French
 * form and kind (extra Japanese spellings become aliases), English kinds, English slugs, and
 * the English forms, romanisations and aliases that the repository already established
 * (`ENGLISH` below, each with its source). Fandom is never a source.
 */
