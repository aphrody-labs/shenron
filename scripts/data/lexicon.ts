// ── Derived outputs ─────────────────────────────────────────────────────────

export function readTerms(root = ROOT): LexiconData {
  return JSON.parse(readFileSync(join(root, TERMS), "utf8")) as LexiconData;
}

/** `terms.json` as written by this script: two-space JSON, terms sorted by id. */
export function renderTerms(data: LexiconData): string {
  const terms = data.terms.toSorted((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return `${JSON.stringify({ $schema: "./terms.schema.json", version: data.version, terms }, null, 2)}\n`;
}

export function renderLegacy(lexicon: Lexicon): string {
  return `${JSON.stringify(lexicon.legacyEntries(), null, 2)}\n`;
}

export function renderGenerated(data: LexiconData): string {
  const lines = [
    `// Generated by ${SELF} from ${TERMS} — do not edit.`,
    "// SPDX-License-Identifier: Apache-2.0",
    'import type { LexiconData } from "./types";',
    "",
    "export const LEXICON_DATA: LexiconData = {",
    `  version: ${data.version},`,
    "  terms: [",
    ...data.terms.map((term) => `    ${JSON.stringify(term)},`),
    "  ],",
    "};",
    "",
  ];
  return lines.join("\n");
}

export interface Output {
  path: string;
  content: string;
}

/** Validation issues of `terms.json` (schema rules, sorted ids, canonical formatting). */
export function check(root = ROOT): {
  issues: string[];
  outputs: Output[];
  lexicon: Lexicon | null;
} {
  const raw = readFileSync(join(root, TERMS), "utf8");
  let doc: unknown;
  try {
    doc = JSON.parse(raw);
  } catch (error) {
    return { issues: [`${TERMS}: ${String(error)}`], outputs: [], lexicon: null };
  }
  const issues = validateLexicon(doc).map((issue) => `${TERMS}: ${issue}`);
  if (issues.length) return { issues, outputs: [], lexicon: null };
  const data = doc as LexiconData;
  if (renderTerms(data) !== raw.replace(/\r\n/g, "\n"))
    issues.push(`${TERMS}: not in canonical form (terms sorted by id, two-space JSON)`);
  const schema = JSON.parse(readFileSync(join(root, SCHEMA), "utf8")) as { properties?: object };
  if (!schema.properties) issues.push(`${SCHEMA}: not a JSON Schema object`);
  const lexicon = new Lexicon(data);
  return {
    issues,
    lexicon,
    outputs: [
      { path: GENERATED, content: renderGenerated(data) },
      { path: LEGACY, content: renderLegacy(lexicon) },
    ],
  };
}

// ── Coverage ────────────────────────────────────────────────────────────────

const pct = (n: number, total: number) => `${((100 * n) / Math.max(1, total)).toFixed(1)} %`;

export function coverageReport(lexicon: Lexicon): string {
  const c = lexicon.coverage();
  const lines = [
    `${c.total} terms — ja ${c.filled.ja} (${pct(c.filled.ja, c.total)}), fr ${c.filled.fr} (${pct(c.filled.fr, c.total)}), en ${c.filled.en} (${pct(c.filled.en, c.total)}), romaji ${c.filled.romaji} (${pct(c.filled.romaji, c.total)})`,
    "",
    "kind            total     ja     fr     en  romaji",
  ];
  for (const kind of KINDS) {
    const k = c.byKind[kind];
    if (!k) continue;
    lines.push(
      `${kind.padEnd(14)} ${String(k.total).padStart(6)} ${String(k.ja).padStart(6)} ${String(k.fr).padStart(6)} ${String(k.en).padStart(6)} ${String(k.romaji).padStart(7)}`,
    );
  }
  return lines.join("\n");
}

