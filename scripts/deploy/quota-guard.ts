/**
 * FinOps Quota Guard for Shenron's Hybrid VPS <-> Vercel/Neon/Cloudflare Topology.
 *
 * Inspects real quota usage across Neon (compute seconds, data transfer, logical storage),
 * Cloudflare (Workers/R2/Vectorize), and Vercel deployments. When any free-tier metric reaches
 * the watermark (default 75%), shifts fr2 Nginx upstream weights off Vercel onto prd VPS
 * (10.200.77.5) so zero overage fees or quota lockouts ever occur.
 */

export interface QuotaMetric {
  provider: "neon" | "cloudflare" | "vercel";
  metric: string;
  used: number;
  limit: number;
  ratio: number;
}

export interface UpstreamWeights {
  mode: "cloud-primary" | "balanced" | "vps-shield";
  vercelWeight: number;
  vpsWeight: number;
  reasons: string[];
}

export function computeUpstreamWeights(
  metrics: readonly QuotaMetric[],
  thresholds = { balanceAt: 0.55, tripAt: 0.75 },
): UpstreamWeights {
  const maxRatio = metrics.reduce((m, x) => Math.max(m, x.ratio), 0);
  const hot = metrics
    .filter((m) => m.ratio >= thresholds.balanceAt)
    .map((m) => `${m.provider}.${m.metric}=${(m.ratio * 100).toFixed(1)}%`);

  if (maxRatio >= thresholds.tripAt) {
    return {
      mode: "vps-shield",
      vercelWeight: 0,
      vpsWeight: 100,
      reasons: hot,
    };
  }
  if (maxRatio >= thresholds.balanceAt) {
    return {
      mode: "balanced",
      vercelWeight: 35,
      vpsWeight: 65,
      reasons: hot,
    };
  }
  return {
    mode: "cloud-primary",
    vercelWeight: 100,
    vpsWeight: 0,
    reasons: [],
  };
}

export function renderNginxWeights(weights: UpstreamWeights): string {
  const lines = [`# Generated by quota-guard.ts (mode=${weights.mode})`];
  if (weights.vercelWeight > 0) {
    lines.push(
      `server 127.0.0.1:18081 weight=${weights.vercelWeight} max_fails=2 fail_timeout=15s;`,
    );
  } else {
    lines.push("server 127.0.0.1:18081 down;");
  }
  if (weights.vpsWeight > 0) {
    lines.push(`server 127.0.0.1:18082 weight=${weights.vpsWeight} max_fails=3 fail_timeout=10s;`);
  } else {
    lines.push("server 127.0.0.1:18082 backup max_fails=3 fail_timeout=10s;");
  }
  return `${lines.join("\n")}\n`;
}

async function fetchNeonMetrics(neonKey: string, projectId: string): Promise<QuotaMetric[]> {
  if (!neonKey) return [];
  const res = await fetch(`https://console.neon.tech/api/v2/projects/${projectId}`, {
    headers: { Authorization: `Bearer ${neonKey}` },
  });
  if (!res.ok) return [];
  const json = (await res.json()) as {
    project?: {
      synthetic_storage_size?: number;
      compute_time_seconds?: number;
      data_transfer_bytes?: number;
      settings?: {
        quota?: {
          compute_time_seconds?: number;
          data_transfer_bytes?: number;
          logical_size_bytes?: number;
        };
      };
    };
  };
  const p = json.project;
  const q = p?.settings?.quota;
  if (!p || !q) return [];
  const out: QuotaMetric[] = [];
  if (q.compute_time_seconds) {
    const used = p.compute_time_seconds ?? 0;
    out.push({
      provider: "neon",
      metric: "compute_seconds",
      used,
      limit: q.compute_time_seconds,
      ratio: used / q.compute_time_seconds,
    });
  }
  if (q.data_transfer_bytes) {
    const used = p.data_transfer_bytes ?? 0;
    out.push({
      provider: "neon",
      metric: "data_transfer_bytes",
      used,
      limit: q.data_transfer_bytes,
      ratio: used / q.data_transfer_bytes,
    });
  }
  if (q.logical_size_bytes) {
    const used = p.synthetic_storage_size ?? 0;
    out.push({
      provider: "neon",
      metric: "logical_size_bytes",
      used,
      limit: q.logical_size_bytes,
      ratio: used / q.logical_size_bytes,
    });
  }
  return out;
}

if (import.meta.main) {
  const applyRemote = process.argv.includes("--apply-fr2");
  const projectId = process.env.NEON_PROJECT_ID || "patient-cloud-06530995";
  const metrics = await fetchNeonMetrics(process.env.NEON_API_KEY || "", projectId);
  const weights = computeUpstreamWeights(metrics);
  const inc = renderNginxWeights(weights);
  console.log(JSON.stringify({ metrics, weights }, null, 2));

  if (applyRemote) {
    const cmd = `sudo tee /etc/nginx/conf.d/shenron-upstream-weights.inc >/dev/null && sudo nginx -t && sudo systemctl reload nginx`;
    const proc = Bun.spawn(["timeout", "15", "ssh", "fr2", cmd], {
      stdin: "pipe",
      stdout: "pipe",
      stderr: "pipe",
    });
    proc.stdin.write(inc);
    proc.stdin.end();
    const [out, err, code] = await Promise.all([
      new Response(proc.stdout).text(),
      new Response(proc.stderr).text(),
      proc.exited,
    ]);
    if (code !== 0) {
      console.error(err);
      process.exit(code);
    }
    console.log("Applied upstream weights on fr2:", weights.mode, out.trim());
  }
}
