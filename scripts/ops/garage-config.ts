// Renders the Garage node config from deploy/garage/cluster.toml and the mesh addresses of
// deploy/environment.json. Usage: bun scripts/ops/garage-config.ts render <node> | nodes
import { join, resolve } from "node:path";

export interface GarageNode {
  name: string;
  triad: string;
  zone: string;
  capacity_gb: number;
  status: "active" | "planned";
}

export interface GarageCluster {
  garage: {
    version: string;
    url: string;
    sha256: string;
    replication_factor: number;
    consistency_mode: string;
    db_engine: string;
    s3_region: string;
  };
  ports: { rpc: number; s3: number; admin: number };
  paths: { config: string; secrets: string; metadata: string; data: string };
  bucket: {
    name: string;
    read_key: string;
    write_key: string;
  };
  serving: {
    public_origin: string;
    manifest_prefix: string;
    dynamic_origin: string;
    origin_node: string;
    origin_port: number;
  };
  nodes: GarageNode[];
}

const root = resolve(import.meta.dir, "../..");

export async function loadCluster(path = join(root, "deploy/garage/cluster.toml")) {
  return Bun.TOML.parse(await Bun.file(path).text()) as unknown as GarageCluster;
}

export async function meshAddresses(path = join(root, "deploy/environment.json")) {
  const env = (await Bun.file(path).json()) as {
    triad: Record<string, { meshIp: string }>;
  };
  return (triad: string) => {
    const ip = env.triad[triad]?.meshIp;
    if (!ip) throw new Error(`triad.${triad}.meshIp missing in deploy/environment.json`);
    return ip;
  };
}

export function renderNodeConfig(cluster: GarageCluster, node: GarageNode, meshIp: string): string {
  const { garage, ports, paths } = cluster;
  if (garage.replication_factor > cluster.nodes.length)
    throw new Error("replication_factor exceeds the declared nodes");
  return `# Generated by scripts/ops/garage-config.ts from deploy/garage/cluster.toml (node ${node.name}). Do not edit by hand.
metadata_dir = "${paths.metadata}"
data_dir = "${paths.data}"
db_engine = "${garage.db_engine}"
replication_factor = ${garage.replication_factor}
consistency_mode = "${garage.consistency_mode}"

rpc_bind_addr = "${meshIp}:${ports.rpc}"
rpc_public_addr = "${meshIp}:${ports.rpc}"
rpc_secret_file = "${paths.secrets}/rpc_secret"

[s3_api]
s3_region = "${garage.s3_region}"
api_bind_addr = "${meshIp}:${ports.s3}"

[admin]
api_bind_addr = "127.0.0.1:${ports.admin}"
admin_token_file = "${paths.secrets}/admin_token"
`;
}

if (import.meta.main) {
  const [command, name] = process.argv.slice(2);
  const cluster = await loadCluster();
  const mesh = await meshAddresses();
  if (command === "render" && name) {
    const node = cluster.nodes.find((entry) => entry.name === name);
    if (!node) throw new Error(`unknown node ${name}`);
    process.stdout.write(renderNodeConfig(cluster, node, mesh(node.triad)));
  } else if (command === "nodes") {
    for (const node of cluster.nodes)
      console.log(
        [node.name, node.status, mesh(node.triad), node.zone, node.capacity_gb].join("\t"),
      );
  } else {
    console.error("usage: garage-config.ts render <node> | nodes");
    process.exit(2);
  }
}
