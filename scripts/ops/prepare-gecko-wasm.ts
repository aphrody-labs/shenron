#!/usr/bin/env bun
// SPDX-License-Identifier: Apache-2.0
/**
 * Stages the Gecko browser build (GameCube/Wii emulator, GPL-3.0, https://github.com/ioncodes/gecko)
 * for the CDN: content-hashed file names (immutable caching), the JS glue rewritten to the hashed
 * wasm, and a generated manifest the site imports. Publish with scripts/ops/publish-wasm-cdn.ts.
 *
 *   bun scripts/ops/prepare-gecko-wasm.ts <wasm-pack pkg dir> [--source-rev <git sha>]
 *
 * The wasm is the wasm-pack release output (fat LTO, simd128, wasm-opt); this script never rebuilds it.
 */
import { createHash } from "node:crypto";
import { join, resolve } from "node:path";

const input = Bun.argv[2];
if (!input) throw new Error("Usage: prepare-gecko-wasm.ts <pkg dir> [--source-rev <sha>]");
const pkg = resolve(input);
const revIndex = Bun.argv.indexOf("--source-rev");
const sourceRev = revIndex > 0 ? (Bun.argv[revIndex + 1] ?? "") : "";

const wasm = new Uint8Array(await Bun.file(join(pkg, "gecko_web_bg.wasm")).arrayBuffer());
if (wasm.length < 1_000_000 || wasm[0] !== 0x00 || wasm[1] !== 0x61 || wasm[2] !== 0x73)
  throw new Error("gecko_web_bg.wasm is missing or not a WebAssembly module");
const digest = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");
const wasmSha = digest(wasm);
const wasmName = `gecko_web_bg.${wasmSha.slice(0, 16)}.wasm`;

const glue = await Bun.file(join(pkg, "gecko_web.js")).text();
if (!glue.includes("gecko_web_bg.wasm"))
  throw new Error("glue does not reference gecko_web_bg.wasm");
const patched = glue.replaceAll("gecko_web_bg.wasm", wasmName);
const jsBytes = new TextEncoder().encode(patched);
const jsName = `gecko_web.${digest(jsBytes).slice(0, 16)}.js`;

const out = resolve(import.meta.dir, "../../apps/site/public/wasm/gecko");
await Bun.$`rm -rf ${out}`.quiet();
await Bun.write(join(out, wasmName), wasm);
await Bun.write(join(out, jsName), jsBytes);
await Bun.write(
  resolve(import.meta.dir, "../../apps/site/src/lib/gecko-wasm.generated.ts"),
  `// Generated by scripts/ops/prepare-gecko-wasm.ts; do not edit.
export const GECKO_WASM = {
  js: ${JSON.stringify(`gecko/${jsName}`)},
  wasm: ${JSON.stringify(`gecko/${wasmName}`)},
  wasmSha256: ${JSON.stringify(wasmSha)},
  wasmBytes: ${wasm.length},
  sourceRevision: ${JSON.stringify(sourceRev)},
} as const;
`,
);
console.log(
  JSON.stringify({ js: jsName, wasm: wasmName, wasmBytes: wasm.length, sha256: wasmSha }),
);
