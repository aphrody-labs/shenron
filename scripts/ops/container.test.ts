import { describe, expect, test } from "bun:test";
import { parseEnvText, serializeEnvMap, prepareContainerSecrets } from "./container-secrets";
import { initContainerDatabases } from "./container-db-init";
import { checkDomainDns } from "./ovh-shenron";
import { existsSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "../..");

describe("container-secrets", () => {
  test("parses env lines and ignores comments/empty lines", () => {
    const raw = `
# Comment
DATABASE_URL=postgres://localhost:5432/db
export API_PORT=5006
KEY_WITH_QUOTES="secret-val"
KEY_WITH_SINGLE='single-val'
    `;
    const map = parseEnvText(raw);
    expect(map.get("DATABASE_URL")).toBe("postgres://localhost:5432/db");
    expect(map.get("API_PORT")).toBe("5006");
    expect(map.get("KEY_WITH_QUOTES")).toBe("secret-val");
    expect(map.get("KEY_WITH_SINGLE")).toBe("single-val");
  });

  test("serializes env map safely with header", () => {
    const map = new Map<string, string>([
      ["A", "1"],
      ["B", "2"],
    ]);
    const serialized = serializeEnvMap(map, "Test Header");
    expect(serialized).toContain("Generated by container-secrets.ts: Test Header");
    expect(serialized).toContain("A=1");
    expect(serialized).toContain("B=2");
  });

  test("generates development container secrets with safe defaults", async () => {
    const outDir = join(ROOT, "var", "test-container-secrets");
    const report = await prepareContainerSecrets({ isProd: false, outDir });
    expect(report.mode).toBe("development");
    expect(report.outFiles.length).toBe(5);
    expect(existsSync(join(outDir, "shenron-site.env"))).toBe(true);
    expect(existsSync(join(outDir, "shenron-bot.env"))).toBe(true);
    expect(existsSync(join(outDir, "deploy.env"))).toBe(true);
  });
});

describe("container-db-init", () => {
  test("dry-run discovers migrations without modifying database", async () => {
    const report = await initContainerDatabases({ dryRun: true });
    expect(report.postgres.status).toBe("ok");
    expect(report.postgres.extensions).toContain("uuid-ossp");
    expect(report.postgres.appliedMigrations.length).toBeGreaterThanOrEqual(20);
    expect(report.sqlite.status).toBe("ok");
    expect(report.sqlite.appliedMigrations.length).toBeGreaterThanOrEqual(15);
  });
});

describe("ovh-shenron", () => {
  test("DNS resolution check performs query safely", async () => {
    const res = await checkDomainDns("dragonballfr.com");
    expect(res.host).toBe("dragonballfr.com");
    // DNS may succeed or report error depending on network; ok field should be boolean
    expect(typeof res.ok).toBe("boolean");
  });
});
