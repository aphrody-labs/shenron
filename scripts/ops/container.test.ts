import { describe, expect, test } from "bun:test";
import { parseEnvText, serializeEnvMap, prepareContainerSecrets } from "./container-secrets";
import { initContainerDatabases } from "./container-db-init";
import { existsSync, statSync } from "node:fs";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

describe("container-secrets", () => {
  test("parses env lines and ignores comments/empty lines", () => {
    const raw = `
# Comment
DATABASE_URL=postgres://localhost:5432/db
export API_PORT=5006
KEY_WITH_QUOTES="secret-val"
KEY_WITH_SINGLE='single-val'
    `;
    const map = parseEnvText(raw);
    expect(map.get("DATABASE_URL")).toBe("postgres://localhost:5432/db");
    expect(map.get("API_PORT")).toBe("5006");
    expect(map.get("KEY_WITH_QUOTES")).toBe("secret-val");
    expect(map.get("KEY_WITH_SINGLE")).toBe("single-val");
  });

  test("serializes env map safely with header", () => {
    const map = new Map<string, string>([
      ["A", "1"],
      ["B", "2"],
    ]);
    const serialized = serializeEnvMap(map, "Test Header");
    expect(serialized).toContain("Generated by container-secrets.ts: Test Header");
    expect(serialized).toContain("A=1");
    expect(serialized).toContain("B=2");
  });

  test("generates development container secrets with safe defaults", async () => {
    const root = await mkdtemp(join(tmpdir(), "shenron-container-secrets-"));
    const outDir = join(root, "out");
    try {
      const report = await prepareContainerSecrets({
        isProd: false,
        outDir,
        devSecretsDir: join(root, "development"),
      });
      expect(report.mode).toBe("development");
      expect(report.outFiles.length).toBe(5);
      expect(existsSync(join(outDir, "shenron-site.env"))).toBe(true);
      expect(existsSync(join(outDir, "shenron-bot.env"))).toBe(true);
      expect(existsSync(join(outDir, "deploy.env"))).toBe(true);
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });

  test("development mode never copies production host secrets", async () => {
    const root = await mkdtemp(join(tmpdir(), "shenron-container-secrets-"));
    const productionDir = join(root, "production");
    const devDir = join(root, "development");
    const outDir = join(root, "out");
    await mkdir(productionDir);
    await mkdir(devDir);
    await writeFile(
      join(productionDir, "shenron-site.env"),
      "DATABASE_URL=postgres://production.invalid/shenron\nBETTER_AUTH_SECRET=production-only-secret\n",
    );
    await writeFile(
      join(productionDir, "shenron-bot.env"),
      "DISCORD_TOKEN_SHENRON=production-token\n",
    );

    try {
      const report = await prepareContainerSecrets({
        isProd: false,
        outDir,
        devSecretsDir: devDir,
      });
      const site = await readFile(join(outDir, "shenron-site.env"), "utf8");
      const bot = await readFile(join(outDir, "shenron-bot.env"), "utf8");
      expect(report.sourcesFound).toEqual([]);
      expect(site).toContain("127.0.0.1:5432/shenron_site");
      expect(site).not.toContain("production");
      expect(bot).not.toContain("DISCORD_TOKEN_SHENRON");
      // POSIX permission bits do not exist on Windows filesystems.
      if (process.platform !== "win32") {
        expect(statSync(outDir).mode & 0o777).toBe(0o700);
        for (const name of report.outFiles) expect(statSync(name).mode & 0o777).toBe(0o600);
      }
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });
});

describe("container-db-init", () => {
  test("dry-run discovers migrations without modifying database", async () => {
    const report = await initContainerDatabases({ dryRun: true });
    expect(report.postgres.status).toBe("ok");
    expect(report.postgres.extensions).toContain("uuid-ossp");
    expect(report.postgres.appliedMigrations.length).toBeGreaterThanOrEqual(20);
    expect(report.sqlite.status).toBe("ok");
    expect(report.sqlite.appliedMigrations.length).toBeGreaterThanOrEqual(15);
  });
});

describe("setup-agent-connectors", () => {
  test("generates Claude, AGY, and Codex configs with tokens", async () => {
    const { buildClaudeMcpConfig, buildAgyMcpConfig, buildCodexTomlConfig, buildOmarReadme } =
      await import("./setup-agent-connectors");
    const fakeTokens = { mcpToken: "test-mcp-token", a2aToken: "test-a2a-token" };
    const claude = buildClaudeMcpConfig(fakeTokens);
    expect(claude.mcpServers["shenron-public"].url).toBe("https://dragonballfr.com/mcp");
    expect(claude.mcpServers["aphrody-tunnel"].headers.Authorization).toBe("Bearer test-mcp-token");

    const agy = buildAgyMcpConfig(fakeTokens);
    expect(agy.mcpServers["shenron-public"].serverUrl).toBe("https://dragonballfr.com/mcp");
    expect(agy.mcpServers["aphrody-tunnel"].headers.Authorization).toBe("Bearer test-mcp-token");

    const codex = buildCodexTomlConfig(fakeTokens);
    expect(codex).toContain("Bearer test-mcp-token");

    const readme = buildOmarReadme(fakeTokens);
    expect(readme).toContain("test-mcp-token");
  });

  test("Omar bundle uses his own Unix account and his wg1 address", async () => {
    const { buildOmarPs1Tunnel, buildOmarShTunnel, buildOmarWireguardConfig } =
      await import("./setup-agent-connectors");
    expect(buildOmarPs1Tunnel()).toContain('$user = "omar"');
    expect(buildOmarShTunnel()).toContain('SSH_USER="omar"');
    expect(buildOmarShTunnel()).not.toContain("ubuntu");
    expect(buildOmarWireguardConfig()).toContain("Address = 10.200.77.10/32");
  });
});
