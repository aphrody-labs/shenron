/**
 * Container secrets manager for Shenron (dragonballfr.com).
 *
 * Discovers and validates credentials held in the Aphrody private store:
 *   - ~/.aphrody/private/shenron/hosts/{dbfr,vps}
 *   - ~/.aphrody/private/shenron/env
 *   - /etc/rose-griffon
 *   - /etc/aphrody
 *
 * Emits deployment environment files under `deploy/docker/env/` (gitignored, 0600)
 * without ever printing plain secret values.
 *
 * Usage:
 *   bun scripts/ops/container-secrets.ts [--prod|--dev] [--out-dir <dir>]
 */

import { chmod, mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "../..");
const DEFAULT_OUT_DIR = join(ROOT, "deploy", "docker", "env");

// Candidate directories for Aphrody private stores
const PRODUCTION_PRIVATE_CANDIDATES = [
  join(homedir(), ".aphrody", "private", "shenron", "hosts", "dbfr"),
  join(homedir(), ".aphrody", "private", "shenron", "hosts", "vps"),
  join(homedir(), ".aphrody", "private", "shenron", "env"),
  process.env.SHENRON_ENV_DIR ?? "/etc/rose-griffon",
  "/etc/aphrody",
];

function privateCandidates(isProd: boolean, devSecretsDir?: string): string[] {
  if (isProd) return PRODUCTION_PRIVATE_CANDIDATES;
  return [
    devSecretsDir
      ? resolve(devSecretsDir)
      : join(homedir(), ".aphrody", "private", "shenron", "development"),
  ];
}

export interface SecretsDiscoveryReport {
  mode: "production" | "development";
  sourcesFound: string[];
  siteKeysCount: number;
  botKeysCount: number;
  botReady: boolean;
  computeKeysCount: number;
  ovhKeysCount: number;
  outFiles: string[];
}

export function parseEnvText(text: string): Map<string, string> {
  const map = new Map<string, string>();
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const match = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=(.*)$/.exec(trimmed);
    if (match) {
      let val = match[2]!.trim();
      if (
        (val.startsWith('"') && val.endsWith('"')) ||
        (val.startsWith("'") && val.endsWith("'"))
      ) {
        val = val.slice(1, -1);
      }
      map.set(match[1]!, val);
    }
  }
  return map;
}

export function serializeEnvMap(env: Map<string, string>, title: string): string {
  const lines = [
    `# SPDX-License-Identifier: Apache-2.0`,
    `# Generated by container-secrets.ts: ${title}`,
  ];
  for (const [key, value] of env.entries()) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) || /[\r\n\0]/.test(value)) {
      throw new Error(`Invalid environment entry: ${key}`);
    }
    lines.push(`${key}=${value}`);
  }
  return lines.join("\n") + "\n";
}

async function findFirstFile(
  roots: string[],
  relativeCandidates: string[],
): Promise<{ path: string; content: string } | null> {
  for (const root of roots) {
    for (const rel of relativeCandidates) {
      const full = join(root, rel);
      if (existsSync(full)) {
        try {
          const content = await readFile(full, "utf8");
          return { path: full, content };
        } catch {
          // Continue to next candidate
        }
      }
    }
  }
  return null;
}

export async function prepareContainerSecrets(
  options: {
    isProd?: boolean;
    outDir?: string;
    devSecretsDir?: string;
  } = {},
): Promise<SecretsDiscoveryReport> {
  const isProd = options.isProd ?? process.env.NODE_ENV === "production";
  const outDir = options.outDir ?? DEFAULT_OUT_DIR;
  await mkdir(outDir, { recursive: true, mode: 0o700 });
  await chmod(outDir, 0o700);
  const roots = privateCandidates(
    isProd,
    options.devSecretsDir ?? process.env.SHENRON_DEV_SECRETS_DIR,
  );

  const sourcesFound: string[] = [];

  // 1. Site secrets
  const siteSources = [
    "shenron-site.env",
    "etc/rose-griffon/shenron-site.env",
    "rose-griffon/shenron-site.env",
  ];
  const siteFound = await findFirstFile(roots, siteSources);
  const siteMap = siteFound ? parseEnvText(siteFound.content) : new Map<string, string>();
  if (siteFound) sourcesFound.push(siteFound.path);

  // 2. Bot secrets
  const botSources = [
    "shenron-bot.env",
    "etc/rose-griffon/shenron-bot.env",
    "rose-griffon/shenron-bot.env",
  ];
  const botFound = await findFirstFile(roots, botSources);
  const botMap = botFound ? parseEnvText(botFound.content) : new Map<string, string>();
  if (botFound) sourcesFound.push(botFound.path);

  // 3. Compute client secrets (Aphrody AI HTTP)
  const computeSources = [
    "shenron-compute-client.env",
    "etc/aphrody/shenron-compute-client.env",
    "aphrody/shenron-compute-client.env",
  ];
  const computeFound = await findFirstFile(roots, computeSources);
  const computeMap = computeFound ? parseEnvText(computeFound.content) : new Map<string, string>();
  if (computeFound) sourcesFound.push(computeFound.path);

  // 4. OVH secrets
  const ovhSources = ["ovh.env", "etc/aphrody/ovh.env", "aphrody/ovh.env"];
  const ovhFound = await findFirstFile(roots, ovhSources);
  const ovhMap = ovhFound ? parseEnvText(ovhFound.content) : new Map<string, string>();
  if (ovhFound) sourcesFound.push(ovhFound.path);

  // In development mode, provide safe fallbacks for missing essentials
  if (!isProd) {
    if (!siteMap.has("DATABASE_URL")) {
      siteMap.set(
        "DATABASE_URL",
        "postgres://shenron:shenron_secure_local_dev@127.0.0.1:5432/shenron_site",
      );
    }
    if (!siteMap.has("BETTER_AUTH_SECRET")) {
      siteMap.set(
        "BETTER_AUTH_SECRET",
        "local_development_better_auth_secret_minimum_32_chars_long",
      );
    }
    if (!siteMap.has("BETTER_AUTH_URL")) {
      siteMap.set("BETTER_AUTH_URL", "http://localhost:3000");
    }
    if (!siteMap.has("SHENRON_ADMIN_TOKEN")) {
      siteMap.set("SHENRON_ADMIN_TOKEN", "local_admin_dev_token_shenron_secret");
    }

    if (!botMap.has("DATABASE_PATH")) {
      botMap.set("DATABASE_PATH", "/app/data/bot.db");
    }
    if (!botMap.has("API_HOST")) {
      botMap.set("API_HOST", "127.0.0.1");
    }
    if (!botMap.has("API_PORT")) {
      botMap.set("API_PORT", "5006");
    }
    const devBotToken = process.env.SHENRON_BOT_DEV_TOKEN ?? process.env.DISCORD_TOKEN_DEV;
    if (devBotToken && !botMap.has("DISCORD_TOKEN_SHENRON")) {
      botMap.set("DISCORD_TOKEN_SHENRON", devBotToken);
    }
  }

  if (isProd) {
    const missing = [
      ...(!siteMap.get("DATABASE_URL") ? ["DATABASE_URL"] : []),
      ...(!siteMap.get("BETTER_AUTH_SECRET") ? ["BETTER_AUTH_SECRET"] : []),
      ...(!(botMap.get("DISCORD_TOKEN_SHENRON") || botMap.get("DISCORD_TOKEN"))
        ? ["DISCORD_TOKEN_SHENRON"]
        : []),
      ...(!botMap.get("GUILD_ID") ? ["GUILD_ID"] : []),
      ...(!botMap.get("OWNER_ID") ? ["OWNER_ID"] : []),
    ];
    if (missing.length) throw new Error(`Production secrets are missing: ${missing.join(", ")}`);
  }

  // Write out files
  const outFiles: string[] = [];

  const siteOut = join(outDir, "shenron-site.env");
  await writeFile(siteOut, serializeEnvMap(siteMap, "Shenron Site Configuration"), {
    encoding: "utf8",
    mode: 0o600,
  });
  await chmod(siteOut, 0o600);
  outFiles.push(siteOut);

  const botOut = join(outDir, "shenron-bot.env");
  await writeFile(botOut, serializeEnvMap(botMap, "Shenron Bot Configuration"), {
    encoding: "utf8",
    mode: 0o600,
  });
  await chmod(botOut, 0o600);
  outFiles.push(botOut);

  const computeOut = join(outDir, "shenron-compute-client.env");
  await writeFile(computeOut, serializeEnvMap(computeMap, "Aphrody Compute Client"), {
    encoding: "utf8",
    mode: 0o600,
  });
  await chmod(computeOut, 0o600);
  outFiles.push(computeOut);

  const ovhOut = join(outDir, "ovh.env");
  await writeFile(ovhOut, serializeEnvMap(ovhMap, "OVH Ops Configuration"), {
    encoding: "utf8",
    mode: 0o600,
  });
  await chmod(ovhOut, 0o600);
  outFiles.push(ovhOut);

  const deployOut = join(outDir, "deploy.env");
  const previousDeploy = existsSync(deployOut)
    ? parseEnvText(await readFile(deployOut, "utf8"))
    : new Map<string, string>();
  const postgresPassword =
    previousDeploy.get("POSTGRES_PASSWORD") ??
    (isProd ? randomBytes(32).toString("hex") : "shenron_secure_local_dev");
  await writeFile(
    deployOut,
    `# SPDX-License-Identifier: Apache-2.0\nSHENRON_PROFILE=${isProd ? "production" : "development"}\nPOSTGRES_PASSWORD=${postgresPassword}\n`,
    { encoding: "utf8", mode: 0o600 },
  );
  await chmod(deployOut, 0o600);
  outFiles.push(deployOut);

  return {
    mode: isProd ? "production" : "development",
    sourcesFound,
    siteKeysCount: siteMap.size,
    botKeysCount: botMap.size,
    botReady: Boolean(
      (botMap.get("DISCORD_TOKEN_SHENRON") || botMap.get("DISCORD_TOKEN")) &&
      botMap.get("GUILD_ID") &&
      botMap.get("OWNER_ID"),
    ),
    computeKeysCount: computeMap.size,
    ovhKeysCount: ovhMap.size,
    outFiles,
  };
}

if (import.meta.main) {
  const isProd = process.argv.includes("--prod");
  const report = await prepareContainerSecrets({ isProd });
  console.log(JSON.stringify(report, null, 2));
}
