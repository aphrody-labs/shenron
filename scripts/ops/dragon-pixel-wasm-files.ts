/**
 * Names and manifest of the Dragon Pixel Bevy build. The build script writes them and the site gate
 * (apps/site/tests/dragon-pixel-wasm.test.ts) reads them back, so the loader can only point at files
 * that the build produces.
 */
import { createHash } from "node:crypto";

/** Stem given to `wasm-bindgen --out-name`; the glue refers to `${OUT_NAME}_bg.wasm`. */
export const OUT_NAME = "dragon_pixel";
export const STAGE_DIR = "dragon-pixel";
export const MANIFEST_PATH = "apps/site/src/lib/dragon-pixel-wasm.generated.ts";
export const PUBLIC_DIR = "apps/site/public/wasm/dragon-pixel";

export interface DragonPixelManifest {
  js: string;
  wasm: string;
  wasmSha256: string;
  /** Bytes of the optimized module as served, the total of the loader's progress bar. */
  wasmBytes: number;
  /** Bytes of the module straight out of wasm-bindgen, before wasm-opt. */
  rawBytes: number;
  sourceRevision: string;
}

export const sha256 = (bytes: Uint8Array): string =>
  createHash("sha256").update(bytes).digest("hex");

/** Content-hashed file name for immutable caching. */
export const hashedName = (stem: string, extension: string, digest: string): string =>
  `${stem}.${digest.slice(0, 16)}.${extension}`;

export const isHashedName = (name: string): boolean =>
  new RegExp(`^${OUT_NAME}(?:_bg)?\\.[a-f0-9]{16}\\.(?:wasm|js)$`).test(name);

export function manifestSource(manifest: DragonPixelManifest): string {
  return `// Generated by scripts/ops/build-dragon-pixel-wasm.ts; do not edit.
export const DRAGON_PIXEL_WASM = {
  js: ${JSON.stringify(manifest.js)},
  wasm: ${JSON.stringify(manifest.wasm)},
  wasmSha256: ${JSON.stringify(manifest.wasmSha256)},
  wasmBytes: ${manifest.wasmBytes},
  rawBytes: ${manifest.rawBytes},
  sourceRevision: ${JSON.stringify(manifest.sourceRevision)},
} as const;
`;
}
